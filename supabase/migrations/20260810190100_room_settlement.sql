-- The researched record is room-scoped, versioned and append-only. Applying a
-- correction inserts a new version and advances rooms.active_settlement_id;
-- the provisional live rows and earlier settlements remain intact as history.

create table if not exists public.room_settlements (
  id uuid primary key default gen_random_uuid(),
  room_id uuid not null references public.rooms(id) on delete cascade,
  version integer not null check (version > 0),
  manifest_hash text not null check (manifest_hash ~ '^[0-9a-f]{64}$'),
  title text not null check (length(btrim(title)) > 0),
  actor text not null check (length(btrim(actor)) > 0),
  bingo_mode text not null check (bingo_mode in ('preserve_live', 'replace')),
  supersedes_id uuid references public.room_settlements(id),
  created_at timestamptz not null default now(),
  unique (id, room_id),
  unique (room_id, version),
  unique (room_id, manifest_hash),
  foreign key (supersedes_id, room_id)
    references public.room_settlements(id, room_id)
);

create table if not exists public.room_settlement_entries (
  id integer generated by default as identity primary key,
  settlement_id uuid not null references public.room_settlements(id) on delete cascade,
  entry_key text not null check (length(btrim(entry_key)) > 0),
  name text not null check (length(btrim(name)) > 0),
  category_id integer references public.categories(id),
  outcome text not null check (outcome in ('resolved', 'void')),
  points integer not null check (points > 0),
  winner_id uuid references public.nominees(id),
  tie_winner_id uuid references public.nominees(id),
  display_order integer not null,
  occurred_at timestamptz,
  warrant jsonb not null,
  unique (settlement_id, entry_key),
  unique (settlement_id, category_id),
  check (
    (outcome = 'resolved' and winner_id is not null)
    or
    (outcome = 'void' and winner_id is null and tie_winner_id is null and category_id is not null)
  ),
  check (winner_id is null or tie_winner_id is distinct from winner_id)
);

create table if not exists public.room_settlement_bingo_marks (
  settlement_id uuid not null references public.room_settlements(id) on delete cascade,
  card_id uuid not null references public.bingo_cards(id) on delete cascade,
  square_index integer not null check (square_index between 0 and 24),
  marked_at timestamptz not null default now(),
  warrant jsonb not null,
  primary key (settlement_id, card_id, square_index)
);

alter table public.rooms
  add column if not exists active_settlement_id uuid references public.room_settlements(id);

alter table public.rooms
  add constraint rooms_active_settlement_same_room
  foreign key (active_settlement_id, id)
  references public.room_settlements(id, room_id);

alter table public.rooms
  add constraint rooms_closed_has_settlement
  check (phase <> 'closed' or active_settlement_id is not null);

