create or replace function public.guard_closed_room()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if old.phase = 'closed'
     and new.phase is distinct from old.phase
     and auth.role() is distinct from 'service_role' then
    raise exception 'a closed room can only be revised by the settlement operator' using errcode = '42501';
  end if;
  return new;
end;
$$;

create trigger guard_closed_room
before update on public.rooms
for each row execute function public.guard_closed_room();

